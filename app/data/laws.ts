export function kindLayer(kind: DocumentKind): KindLayer {
  if (kind === "กฎหมายแม่บท") return "แม่บท";
  if (kind === "ประมวลกฎหมาย") return "ประมวล";
  if (kind === "บทบัญญัติรัฐธรรมนูญ") return "รัฐธรรมนูญ";
  if (kind === "กฎหมายลำดับรอง") return "ลำดับรอง";
  return "มณฑลหรือรัฐ";
}

export function matchesKindFilter(law: Law, filter: KindFilter) {
  if (filter === "ทั้งหมด") return true;
  if (filter === "มณฑลหรือรัฐ") {
    return law.kind === "กฎหมายระดับมณฑล" || law.kind === "ประมวลกฎหมายระดับรัฐ";
  }
  return law.kind === filter;
}

