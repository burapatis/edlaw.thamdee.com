export function parseCompareIds(value: string | null) {
  if (!value) return [];
  const allowed = new Set(laws.map((law) => law.id));
  return [...new Set(value.split(",").map((id) => id.trim()).filter((id) => allowed.has(id)))].slice(
    0,
    MAX_COMPARE,
  );
}

