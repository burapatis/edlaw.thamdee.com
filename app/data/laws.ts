export function parseBriefId(value: string | null | undefined) {
  if (value && drafterBriefs.some((brief) => brief.topicId === value)) return value;
  return drafterBriefs[0]?.topicId ?? "aims";
}

export function findBrief(topicId: string | null | undefined) {
  const id = parseBriefId(topicId);
  return drafterBriefs.find((brief) => brief.topicId === id) ?? drafterBriefs[0] ?? null;
}

